/** Races grouped by MM-DD, for the "on this day" angle. */
export function racesByMonthDay() {
  const key = '__racesByMonthDay';
  if (cache.has(key)) return cache.get(key);
  const map = new Map();
  for (const r of racesIndex()) {
    if (!r.date || !r.completed) continue;
    const md = r.date.slice(5, 10);
    if (!map.has(md)) map.set(md, []);
    map.get(md).push(r);
  }
  cache.set(key, map);
  return map;
}
